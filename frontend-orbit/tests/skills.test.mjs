import assert from 'node:assert/strict';
import { once } from 'node:events';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { chromium } from 'playwright';
import { setAccount } from '../../server-orbit/dist/auth.js';
import { configuration } from '../../server-orbit/dist/config.js';
import { openDatabase } from '../../server-orbit/dist/database.js';
import { createOrbitServer } from '../../server-orbit/dist/http.js';
import { SkillReferences } from '../../server-orbit/dist/skills/references.js';
import { Skills } from '../../server-orbit/dist/skills/service.js';

test('Skills UI creates and versions complete packages, previews safe Markdown, imports and isolates org data', { timeout: 90_000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'orbit-skills-browser-'));
  const source = join(directory, 'project/skills/original');
  await mkdir(join(source, 'references'), { recursive: true });
  await writeFile(join(source, 'SKILL.md'), '---\nname: review-guidelines\ndescription: Imported guidelines\n---\n\nRead [reference](references/original.md).\n');
  await writeFile(join(source, 'references/original.md'), 'Original imported reference');
  const database = openDatabase(directory);
  await setAccount(database, 'skill-user', 'test-only-password');
  const server = createOrbitServer(configuration({ ORBIT_STATE_DIR: directory, ORBIT_PORT: '0' }), database);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const executablePath = process.env.ORBIT_TEST_BROWSER || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
  const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); database.close(); await rm(directory, { recursive: true, force: true }); });
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1500, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const screenshot = async name => {
    if (!process.env.ORBIT_TEST_ARTIFACT_DIR) return;
    await mkdir(process.env.ORBIT_TEST_ARTIFACT_DIR, { recursive: true });
    await page.screenshot({ path: join(process.env.ORBIT_TEST_ARTIFACT_DIR, `skills-${name}.png`), fullPage: true });
  };
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByLabel('账号', { exact: true }).fill('skill-user');
  await page.getByLabel('密码', { exact: true }).fill('test-only-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByLabel('组织名称').fill('Skills Studio');
  await page.getByRole('button', { name: '创建并进入工作空间' }).click();
  const nav = page.getByRole('navigation', { name: '功能导航' });
  await nav.getByRole('button', { name: 'Skills', exact: true }).click();
  await page.getByRole('heading', { name: '还没有安装技能' }).waitFor();
  await page.getByText('New', { exact: true }).click();
  await page.getByRole('button', { name: 'Create a skill' }).click();
  await page.getByLabel('名称', { exact: true }).fill('code-review');
  await page.getByLabel('说明', { exact: true }).fill('Review code and evidence');
  await page.getByLabel('指令正文').fill('# Review\n\n[Checklist](references/checklist.md)\n\n![Example](assets/example.png)\n\n<script>window.skillXss = 1</script>\n<img src=x onerror="window.skillXss = 1">');
  await page.getByRole('button', { name: '创建技能', exact: true }).click();
  await page.getByText('版本 1', { exact: true }).waitFor();
  const editor = page.getByLabel('文件内容', { exact: true });
  const original = await editor.inputValue();
  await editor.fill(original.replace('name: "code-review"', 'name: "review-guidelines"').replace('description: "Review code and evidence"', 'description: "Updated code review guidance"'));
  await page.getByRole('button', { name: '新建文件', exact: true }).click();
  await page.getByLabel('文件路径', { exact: true }).fill('references/checklist.md');
  await page.getByRole('button', { name: '确定', exact: true }).click();
  await editor.fill('# Checklist\n\n- Verify meaningful tests');
  await page.getByRole('button', { name: '重命名', exact: true }).click();
  await page.getByLabel('新路径', { exact: true }).fill('references/renamed.md');
  await page.getByRole('button', { name: '确定', exact: true }).click();
  await page.getByRole('button', { name: '重命名', exact: true }).click();
  await page.getByLabel('新路径', { exact: true }).fill('references/checklist.md');
  await page.getByRole('button', { name: '确定', exact: true }).click();
  await page.getByRole('button', { name: 'SKILL.md', exact: true }).click();
  await page.getByRole('button', { name: '新建目录', exact: true }).click();
  await page.getByLabel('目录路径', { exact: true }).fill('assets');
  await page.getByRole('button', { name: '确定', exact: true }).click();
  await page.getByLabel('选择上传文件').setInputFiles([
    { name: 'example.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jwZkAAAAASUVORK5CYII=', 'base64') },
    { name: 'raw.bin', mimeType: 'application/octet-stream', buffer: Buffer.from([0, 255, 1]) },
  ]);
  await page.getByRole('button', { name: 'assets/raw.bin', exact: true }).waitFor();
  await page.getByRole('button', { name: 'SKILL.md', exact: true }).click();
  await page.getByRole('button', { name: '预览', exact: true }).click();
  await page.getByRole('heading', { name: 'Review', exact: true }).waitFor();
  await page.getByRole('article', { name: 'Markdown 预览' }).getByRole('heading', { name: 'review-guidelines', exact: true }).waitFor();
  assert.match(await page.getByRole('article', { name: 'Markdown 预览' }).innerText(), /Updated code review guidance/);
  assert.equal(await page.evaluate(() => window.skillXss), undefined);
  assert.match(await page.getByRole('img', { name: 'Example' }).getAttribute('src'), /^data:image\/png;base64,/);
  await page.getByRole('link', { name: 'Checklist', exact: true }).click();
  assert.match(await editor.inputValue(), /Verify meaningful tests/);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('版本 2', { exact: true }).waitFor();
  await page.getByRole('heading', { name: 'review-guidelines', exact: true }).waitFor();
  await screenshot('editor');
  await page.getByRole('button', { name: 'assets/raw.bin', exact: true }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载文件', exact: true }).first().click();
  assert.equal((await downloaded).suggestedFilename(), 'raw.bin');
  await page.getByRole('button', { name: '返回 Installed skills', exact: true }).click();
  await page.getByText('New', { exact: true }).click();
  await page.getByRole('button', { name: 'Import skills from project', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('Local project');
  await page.getByLabel('本地工作目录', { exact: true }).fill(join(directory, 'project'));
  await page.getByRole('button', { name: '保存项目', exact: true }).click();
  await page.getByRole('button', { name: '扫描技能', exact: true }).click();
  await page.getByRole('checkbox', { name: '导入 review-guidelines', exact: true }).check();
  await page.getByRole('button', { name: '导入所选技能', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert.match(await page.getByRole('alert').innerText(), /同名/);
  await page.getByLabel('导入名称 review-guidelines', { exact: true }).fill('imported-guidelines');
  await page.getByRole('button', { name: '导入所选技能', exact: true }).click();
  await page.getByRole('heading', { name: 'Installed skills', exact: true }).waitFor();
  await page.getByLabel('搜索技能').fill('imported-guidelines');
  const imported = page.getByRole('button', { name: /imported-guidelines/ });
  await imported.waitFor();
  await imported.click();
  await page.getByRole('button', { name: 'references/original.md', exact: true }).waitFor();
  await writeFile(join(source, 'references/original.md'), 'Changed in source');
  await page.getByRole('button', { name: 'references/original.md', exact: true }).click();
  assert.equal(await editor.inputValue(), 'Original imported reference');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('heading', { name: 'Installed skills', exact: true }).waitFor();
  assert.equal(database.prepare('SELECT count(*) AS count FROM skills WHERE deleted_at IS NOT NULL').get().count, 1);
  const row = database.prepare('SELECT id, org_id FROM skills WHERE name = ? AND deleted_at IS NULL').get('review-guidelines');
  const refs = new SkillReferences(new Skills(database, directory)); refs.set(row.org_id, 'agent-test', [row.id]);
  await page.getByRole('button', { name: /review-guidelines/ }).click();
  await page.getByText('1 位 Agent 引用', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '删除', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: '返回 Installed skills', exact: true }).click();
  await screenshot('list');
  await page.getByRole('button', { name: /^切换组织，当前/ }).click();
  await page.getByRole('button', { name: '创建组织', exact: true }).click();
  await page.getByLabel('组织名称').fill('Empty Studio');
  await page.getByRole('button', { name: '创建组织', exact: true }).click();
  await nav.getByRole('button', { name: 'Skills', exact: true }).click();
  await page.getByRole('heading', { name: '还没有安装技能' }).waitFor();
  assert.deepEqual(errors, []);
});
